// Writes icons.js: the Lucide icons the mockup uses, as inline SVG markup.
// The app uses the same icons through lucide-react, bundled, so it works offline (UI-9).
//
//   npm pack lucide@0.460.0 && tar xzf lucide-0.460.0.tgz
//   node docs/mockups/icons.mjs ./package
//
// Lucide is ISC licensed: https://lucide.dev/license
import { writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const pkg = resolve(process.argv[2] || "node_modules/lucide");
const { icons } = createRequire(import.meta.url)(join(pkg, "dist/umd/lucide.js"));

// Our name → Lucide name.
const USE = {
  home: "House", api: "Plug", layers: "Layers", agent: "Bot", activity: "Activity", settings: "Settings",
  search: "Search", copy: "Copy", check: "Check", x: "X", plus: "Plus", chat: "MessageSquareText", play: "Play",
  lock: "Lock", key: "KeyRound", shield: "ShieldCheck", import: "Download", alert: "TriangleAlert", info: "Info",
  bulb: "Lightbulb", eye: "Eye", clock: "Clock", folder: "Folder", code: "CodeXml", terminal: "SquareTerminal",
  link: "Link", ban: "Ban", chev: "ChevronRight", file: "File", sun: "Sun", moon: "Moon", github: "Github",
  star: "Star", book: "BookOpen", help: "CircleHelp", globe: "Globe", json: "FileJson", fileplus: "FilePlus",
  tree: "FolderTree", arrowr: "ArrowRight", arrowl: "ArrowLeft", upload: "Upload", ext: "ExternalLink",
  inbox: "Inbox", zap: "Zap", bug: "Bug", scale: "Scale", history: "History", flask: "FlaskConical", monitor: "Monitor",
};

const render = ([tag, attrs, children = []]) =>
  `<${tag}${Object.entries(attrs).map(([k, v]) => ` ${k}="${v}"`).join("")}${children.length ? `>${children.map(render).join("")}</${tag}>` : "/>"}`;

const out = {};
for (const [name, lucide] of Object.entries(USE)) {
  const node = icons[lucide];
  if (!node) throw new Error(`Lucide has no icon named ${lucide}`);
  out[name] = node[2].map(render).join("");
}
const dir = dirname(fileURLToPath(import.meta.url));
writeFileSync(join(dir, "icons.js"), `// Generated by icons.mjs from Lucide 0.460.0 (ISC). Don't edit by hand.\nconst LUCIDE = ${JSON.stringify(out, null, 1)};\n`);
console.log(`wrote ${Object.keys(out).length} icons`);
