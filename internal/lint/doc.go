package lint

import (
	"fmt"
	"strings"
)

// Markdown renders docs/lint-rules.md from Rules.
func Markdown() string {
	var b strings.Builder
	b.WriteString("# Lint rules\n\n")
	b.WriteString("<!-- Generated by `go run ./tools/lintdoc > docs/lint-rules.md`. Do not edit. -->\n\n")
	b.WriteString("mcpDeck checks every tool when it is saved, in the editor as you type, with\n")
	b.WriteString("`mcpdeck lint <toolkit>` and with the admin MCP `lint` tool. The checks are plain\n")
	b.WriteString("code in `internal/lint`; no model runs, so the same input gives the same findings.\n\n")
	b.WriteString("| Severity | Meaning |\n|---|---|\n")
	b.WriteString("| block | Invalid by the MCP spec, a leaked credential, or a write tool marked read-only. Saving is refused. |\n")
	b.WriteString("| warn | Works, but costs tokens or makes agents pick the wrong tool. Shown, and fails `mcpdeck lint --strict`. |\n")
	b.WriteString("| hint | Usually helps. Shown only. |\n\n")
	b.WriteString("Each finding carries the rule, a short explanation, a fix and the source below.\n")
	b.WriteString("A toolkit's score starts at 100 and loses 25 per block and 5 per warning.\n")
	for _, sec := range Sections {
		fmt.Fprintf(&b, "\n## %s\n\n| Rule | Severity | Check | Fix | Sources |\n|---|---|---|---|---|\n", sec)
		for _, r := range Rules {
			if r.Section != sec {
				continue
			}
			var src []string
			for _, k := range r.Sources {
				src = append(src, "["+k+"](#sources)")
			}
			fmt.Fprintf(&b, "| `%s` | %s | %s | %s | %s |\n", r.ID, r.Severity, esc(r.Check), esc(r.Fix), strings.Join(src, ", "))
		}
	}
	b.WriteString("\n## Sources\n\n")
	for _, s := range Sources {
		fmt.Fprintf(&b, "- `%s`: [%s](%s)\n", s.Key, s.Title, s.URL)
	}
	return b.String()
}

func esc(s string) string { return strings.ReplaceAll(s, "|", "\\|") }
